def allowed(policy, session, staff) -> bool:
    if policy == "all":
        return True
    if policy == "admin":
        return staff.role == "admin"
    return policy in PERMISSIONS and policy in permissions_of(session, staff)


def require_role(path, method, session, staff):
    policy = ROUTE_POLICY.get((method, path))
    if not allowed(policy, session, staff):
        raise HTTPException(
            403,
            "僅管理員可使用此功能" if policy == "admin"
            else "此帳號沒有這項功能的權限" if policy in PERMISSIONS
            else "此帳號僅能檢視資料",
        )
