def require_role(path, method, role):
    policy = ROUTE_POLICY.get((method, path))
    if role not in ROLE_SETS.get(policy, set()):
        raise HTTPException(
            403, "僅管理員可使用此功能" if policy == "admin" else "此帳號僅能檢視資料"
        )
